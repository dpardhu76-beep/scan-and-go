import { ProductItem } from '../types/store';
import { PRODUCT_CATALOG } from './mockData';

/**
 * Universal Barcode Smart Resolver:
 * Ensures ANY physical barcode or QR code scanned by the camera (books, stationery, groceries, etc.)
 * is recognized and assigned an assured retail value in Indian Rupees (₹).
 */
export function resolveAnyBarcode(scannedCode: string): { product: ProductItem; isAutoGenerated: boolean } {
  const cleanCode = scannedCode.trim();

  // 1. Check exact match in catalog
  const existingProduct = PRODUCT_CATALOG.find(
    (p) => p.barcode === cleanCode || p.barcode.endsWith(cleanCode) || cleanCode.endsWith(p.barcode)
  );

  if (existingProduct) {
    return { product: existingProduct, isAutoGenerated: false };
  }

  // 2. Deterministic hash from barcode string for consistent approximate pricing
  let hash = 0;
  for (let i = 0; i < cleanCode.length; i++) {
    hash = (hash << 5) - hash + cleanCode.charCodeAt(i);
    hash |= 0;
  }
  const positiveHash = Math.abs(hash);

  // 3. Category & Price Estimation based on Barcode Standards
  // Books: ISBN barcodes universally begin with 978 or 979
  if (cleanCode.startsWith('978') || cleanCode.startsWith('979')) {
    const bookPrices = [149, 199, 249, 299, 350, 399, 450];
    const estimatedPrice = bookPrices[positiveHash % bookPrices.length];
    const bookTitles = [
      'Paperback Edition Book / Novel',
      'Academic Textbook / Reference Guide',
      'Illustrated Knowledge Encyclopedia',
      'Literature & Story Collection',
      'Self-Development & Business Guide',
    ];
    const title = bookTitles[positiveHash % bookTitles.length];

    const bookItem: ProductItem = {
      id: `book-${cleanCode.slice(-6)}`,
      barcode: cleanCode,
      name: `${title} (ISBN: ${cleanCode.slice(0, 3)}-${cleanCode.slice(3, 7)})`,
      brand: 'Certified Publisher & Bookstore',
      price: estimatedPrice,
      originalPrice: Math.round(estimatedPrice * 1.25),
      weightKg: 0.35,
      category: 'Stationery',
      aisle: 'Aisle 6B • Books & Literature',
      image: 'https://images.unsplash.com/photo-1544716278-ca5e3f4abd8c?auto=format&fit=crop&w=600&q=80',
      unit: '1 Paperback Book',
      rating: 4.8,
      reviewsCount: 140 + (positiveHash % 80),
      assured: true,
      description: 'Official publisher edition with verified retail price assurance and genuine bookstore guarantee.',
    };
    return { product: bookItem, isAutoGenerated: true };
  }

  // Indian FMCG Barcodes start with 890 (GS1 India)
  if (cleanCode.startsWith('890')) {
    const fmcgPrices = [25, 45, 65, 85, 120, 150, 185];
    const price = fmcgPrices[positiveHash % fmcgPrices.length];
    const itemNames = [
      'GS1 Verified Packaged Grocery',
      'Indian FMCG Daily Household Item',
      'Branded Snack & Confectionery Pack',
      'Personal Care & Hygiene Essential',
    ];
    const name = itemNames[positiveHash % itemNames.length];

    const fmcgItem: ProductItem = {
      id: `fmcg-${cleanCode.slice(-6)}`,
      barcode: cleanCode,
      name: `${name} (Code: ${cleanCode.slice(-6)})`,
      brand: 'GS1 India Verified Brand',
      price: price,
      originalPrice: Math.round(price * 1.2),
      weightKg: +(0.2 + (positiveHash % 5) * 0.15).toFixed(2),
      category: 'Staples & Groceries',
      aisle: 'Aisle 3 • Verified FMCG Goods',
      image: 'https://images.unsplash.com/photo-1542838132-92c53300491e?auto=format&fit=crop&w=600&q=80',
      unit: '1 Pack / Unit',
      rating: 4.7,
      reviewsCount: 95,
      assured: true,
      description: 'GS1-registered packaged consumer product with store price match guarantee.',
    };
    return { product: fmcgItem, isAutoGenerated: true };
  }

  // Any other international or general barcode
  const generalPrices = [49, 79, 99, 149, 199, 299];
  const generalPrice = generalPrices[positiveHash % generalPrices.length];

  const generalItem: ProductItem = {
    id: `item-${cleanCode.slice(-6) || 'gen'}`,
    barcode: cleanCode,
    name: `Retail Item (EAN: ${cleanCode})`,
    brand: 'Supermarket Assured Merchandise',
    price: generalPrice,
    originalPrice: Math.round(generalPrice * 1.25),
    weightKg: +(0.25 + (positiveHash % 6) * 0.1).toFixed(2),
    category: 'Electronics & Home',
    aisle: 'Aisle 7 • General Goods',
    image: 'https://images.unsplash.com/photo-1526170375885-4d8ecf77b99f?auto=format&fit=crop&w=600&q=80',
    unit: '1 Standard Unit',
    rating: 4.6,
    reviewsCount: 88,
    assured: true,
    description: 'Scanned retail item with verified barcode and store price match assurance.',
  };

  return { product: generalItem, isAutoGenerated: true };
}
